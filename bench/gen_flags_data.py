"""room_lab/flags.json -> room_lab/flags_data.h (the registry compiled into the app, for the SETTINGS menu).
    python3 bench/gen_flags_data.py          write it
    python3 bench/gen_flags_data.py --check  exit 1 if the header is out of date (run_offline_tests.sh)"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'room_lab/flags.json')).read()
assert ')FJ"' not in src
out = ('// Generated by bench/gen_flags_data.py from room_lab/flags.json; do not edit. The offline suite checks it is current.\n'
       '#pragma once\n\ninline const char* kFlagsJson = R"FJ(' + src + ')FJ";\n')
path = os.path.join(root, 'room_lab/flags_data.h')
if '--check' in sys.argv:
    cur = open(path).read() if os.path.exists(path) else ''
    if cur != out:
        print('room_lab/flags_data.h is out of date: python3 bench/gen_flags_data.py'); sys.exit(1)
    print('flags_data.h matches flags.json'); sys.exit(0)
open(path, 'w').write(out)
print('wrote', path)
