"""Generate room_lab/font_unifont.h from a GNU Unifont .hex file (SIL OFL 1.1; room_lab/third_party/unifont/OFL.txt).
Ranges: printable ASCII, Latin-1, general punctuation and Cyrillic, as 8-pixel-wide glyphs only (16 rows).
    python3 bench/gen_font.py /path/to/unifont-13.0.06.hex > room_lab/font_unifont.h"""
import sys
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x400, 0x45F), (0x2010, 0x2027), (0x2030, 0x203A), (0x20AC, 0x20AC), (0x2190, 0x2193), (0x2022, 0x2022)]
want = {c for a, b in RANGES for c in range(a, b + 1)}
glyphs = {}
for line in open(sys.argv[1]):
    cp, bits = line.strip().split(':')
    cp = int(cp, 16)
    if cp in want and len(bits) == 32: glyphs[cp] = [int(bits[i:i + 2], 16) for i in range(0, 32, 2)]
print('// Generated by bench/gen_font.py from GNU Unifont 13.0.06 (SIL Open Font License 1.1: room_lab/third_party/unifont/OFL.txt).')
print('// 8x16 bitmap glyphs, row 0 at the top, bit 7 = leftmost pixel. ASCII, Latin-1, Cyrillic, common punctuation.')
print('#pragma once\n#include <cstdint>\n#include <string>\n\nnamespace unifont {\n')
print('struct Glyph { uint16_t cp; uint8_t rows[16]; };')
print(f'static const Glyph kGlyphs[{len(glyphs)}] = {{')
for cp in sorted(glyphs): print('    {0x%04X, {%s}},' % (cp, ','.join(str(r) for r in glyphs[cp])))
print('};')
print('''inline const Glyph* find(uint32_t cp) {
    int lo = 0, hi = (int)(sizeof kGlyphs / sizeof kGlyphs[0]) - 1;
    while (lo <= hi) { int m = (lo + hi) / 2; if (kGlyphs[m].cp == cp) return &kGlyphs[m]; if (kGlyphs[m].cp < cp) lo = m + 1; else hi = m - 1; }
    return nullptr;
}
// Next code point from UTF-8 at s[i] (advances i); malformed bytes come back as '?'.
inline uint32_t next(const std::string& s, size_t& i) {
    unsigned char c = (unsigned char)s[i++];
    if (c < 0x80) return c;
    int n = (c & 0xE0) == 0xC0 ? 1 : (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : -1;
    if (n < 0) return '?';
    uint32_t cp = c & (0x3F >> n);
    for (int k = 0; k < n; k++) { if (i >= s.size() || ((unsigned char)s[i] & 0xC0) != 0x80) return '?'; cp = (cp << 6) | ((unsigned char)s[i++] & 0x3F); }
    return cp;
}
inline size_t length(const std::string& s) { size_t n = 0; for (size_t i = 0; i < s.size();) { next(s, i); n++; } return n; }
''')
print('}  // namespace unifont')
